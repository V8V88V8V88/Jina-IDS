import re
import json
import os
import logging
from typing import Dict, List, Optional, Any, Set
from dataclasses import dataclass, field
from datetime import datetime
from collections import defaultdict
from netaddr import IPNetwork, IPAddress

logger = logging.getLogger("JinaIDS.RuleEngine")


@dataclass
class DetectionRule:
    """Represents a single detection rule."""
    id: str
    name: str
    pattern: str = ""
    severity: str = "medium"
    category: str = "generic"
    description: str = ""
    mitre_attack: str = ""
    enabled: bool = True
    compiled_pattern: Optional[re.Pattern] = None
    
    def __post_init__(self):
        if self.pattern:
            try:
                self.compiled_pattern = re.compile(self.pattern, re.IGNORECASE | re.MULTILINE)
            except re.error as e:
                logger.warning(f"Invalid regex pattern in rule {self.id}: {e}")
                self.enabled = False


@dataclass
class Alert:
    """Security alert generated by detection."""
    timestamp: datetime
    rule_id: str
    rule_name: str
    severity: str
    category: str
    description: str
    src_ip: str = ""
    dst_ip: str = ""
    src_port: int = 0
    dst_port: int = 0
    protocol: str = ""
    matched_content: str = ""
    mitre_attack: str = ""
    raw_data: Dict = field(default_factory=dict)
    
    def to_dict(self) -> Dict:
        return {
            "timestamp": self.timestamp.isoformat(),
            "rule_id": self.rule_id,
            "rule_name": self.rule_name,
            "severity": self.severity,
            "category": self.category,
            "description": self.description,
            "src_ip": self.src_ip,
            "dst_ip": self.dst_ip,
            "src_port": self.src_port,
            "dst_port": self.dst_port,
            "protocol": self.protocol,
            "matched_content": self.matched_content[:200] if self.matched_content else "",
            "mitre_attack": self.mitre_attack
        }
    
    def __str__(self) -> str:
        return (f"[{self.severity.upper()}] {self.rule_name} | "
                f"{self.src_ip}:{self.src_port} -> {self.dst_ip}:{self.dst_port} | "
                f"MITRE: {self.mitre_attack}")


class RuleEngine:
    """
    Professional signature-based detection engine.
    
    Features:
    - CEH-level attack signatures
    - MITRE ATT&CK mapping
    - IP blacklist/whitelist
    - Payload pattern matching
    - Port-based anomaly detection
    - Rate limiting detection
    """
    
    SEVERITY_PRIORITY = {
        "critical": 1,
        "high": 2,
        "medium": 3,
        "low": 4,
        "info": 5
    }
    
    def __init__(self, rules_file: str = "data/rules/default_rules.json"):
        self.rules_file = rules_file
        self.rules: Dict[str, DetectionRule] = {}
        self.ip_blacklist: Set[IPNetwork] = set()
        self.ip_whitelist: Set[IPNetwork] = set()
        self.suspicious_ports: Dict[str, Set[int]] = defaultdict(set)
        self.protocol_rules: Dict[str, Dict] = {}
        self.network_signatures: List[Dict] = []
        self.signature_config: Dict = {}
        
        # Rate limiting tracking
        self.rate_counters: Dict[str, Dict] = defaultdict(lambda: defaultdict(int))
        self.rate_timestamps: Dict[str, Dict] = defaultdict(lambda: defaultdict(list))
        
        # Load rules
        self._load_rules()
    
    def _load_rules(self):
        """Load detection rules from configuration file."""
        if not os.path.exists(self.rules_file):
            logger.warning(f"Rules file not found: {self.rules_file}")
            self._load_default_rules()
            return
        
        try:
            with open(self.rules_file, "r") as f:
                config = json.load(f)
            
            # Load payload signatures
            for sig in config.get("payload_signatures", []):
                rule = DetectionRule(
                    id=sig.get("id", ""),
                    name=sig.get("name", ""),
                    pattern=sig.get("pattern", ""),
                    severity=sig.get("severity", "medium"),
                    category=sig.get("category", "generic"),
                    description=sig.get("description", ""),
                    mitre_attack=sig.get("mitre_attack", ""),
                    enabled=sig.get("enabled", True)
                )
                if rule.enabled and rule.compiled_pattern:
                    self.rules[rule.id] = rule
            
            # Load IP blacklist
            for ip_range in config.get("ip_blacklist", []):
                try:
                    # Skip private ranges from blacklist (they're just examples)
                    if not any(ip_range.startswith(prefix) for prefix in ["10.", "172.16", "192.168"]):
                        self.ip_blacklist.add(IPNetwork(ip_range))
                except Exception as e:
                    logger.warning(f"Invalid IP range in blacklist: {ip_range} - {e}")
            
            # Load suspicious ports
            for category, ports in config.get("suspicious_ports", {}).items():
                self.suspicious_ports[category] = set(ports)
            
            # Load protocol-specific rules
            self.protocol_rules = config.get("protocol_anomalies", {})
            
            # Load network signatures
            self.network_signatures = config.get("network_signatures", [])
            
            # Load signature configs (for rate-based detection)
            self.signature_config = config.get("signatures", {})
            
            logger.info(f"Loaded {len(self.rules)} payload signatures")
            logger.info(f"Loaded {len(self.ip_blacklist)} IP blacklist entries")
            logger.info(f"Loaded {sum(len(p) for p in self.suspicious_ports.values())} suspicious ports")
            
        except Exception as e:
            logger.error(f"Error loading rules: {e}")
            self._load_default_rules()
    
    def _load_default_rules(self):
        """Load minimal default rules if config not available."""
        default_signatures = [
            {
                "id": "SQL-INJECTION-BASIC",
                "name": "SQL Injection Attempt",
                "pattern": r"(?i)(union\s+select|or\s+1\s*=\s*1|'\s*or\s+')",
                "severity": "critical",
                "category": "web_attack",
                "mitre_attack": "T1190"
            },
            {
                "id": "XSS-BASIC",
                "name": "Cross-Site Scripting",
                "pattern": r"(?i)(<script|javascript:|on\w+\s*=)",
                "severity": "high",
                "category": "web_attack",
                "mitre_attack": "T1059.007"
            },
            {
                "id": "CMD-INJECTION-BASIC",
                "name": "Command Injection",
                "pattern": r"(;\s*(cat|ls|wget|curl)|`[^`]+`|\$\([^)]+\))",
                "severity": "critical",
                "category": "command_injection",
                "mitre_attack": "T1059"
            },
            {
                "id": "PATH-TRAVERSAL-BASIC",
                "name": "Path Traversal",
                "pattern": r"(\.\./|\.\.\\|%2e%2e)",
                "severity": "high",
                "category": "file_access",
                "mitre_attack": "T1083"
            }
        ]
        
        for sig in default_signatures:
            rule = DetectionRule(**sig)
            if rule.compiled_pattern:
                self.rules[rule.id] = rule
        
        logger.info(f"Loaded {len(self.rules)} default rules")
    
    def add_rule(self, rule: DetectionRule) -> bool:
        """Add a new detection rule."""
        if rule.enabled and rule.compiled_pattern:
            self.rules[rule.id] = rule
            return True
        return False
    
    def check_ip_blacklist(self, ip: str) -> Optional[Alert]:
        """Check if IP is blacklisted."""
        if not ip:
            return None
        
        try:
            ip_addr = IPAddress(ip)
            for blocked_net in self.ip_blacklist:
                if ip_addr in blocked_net:
                    return Alert(
                        timestamp=datetime.now(),
                        rule_id="BLACKLIST-IP",
                        rule_name="Blacklisted IP Address",
                        severity="high",
                        category="threat_intel",
                        description=f"Traffic from/to blacklisted IP: {ip}",
                        src_ip=ip,
                        mitre_attack="T1071"
                    )
        except Exception as e:
            logger.debug(f"IP blacklist check error: {e}")
        
        return None
    
    def check_suspicious_port(self, port: int, category: str = "all") -> Optional[str]:
        """Check if port is in suspicious list."""
        if category == "all":
            for cat, ports in self.suspicious_ports.items():
                if port in ports:
                    return cat
        elif port in self.suspicious_ports.get(category, set()):
            return category
        return None
    
    def check_payload(self, payload: bytes, packet_info: Any = None) -> List[Alert]:
        """Check payload against all signature rules."""
        alerts = []
        
        if not payload:
            return alerts
        
        try:
            # Convert bytes to string for pattern matching
            text = payload.decode('utf-8', errors='ignore')
            
            for rule_id, rule in self.rules.items():
                if not rule.enabled or not rule.compiled_pattern:
                    continue
                
                match = rule.compiled_pattern.search(text)
                if match:
                    alert = Alert(
                        timestamp=datetime.now(),
                        rule_id=rule.id,
                        rule_name=rule.name,
                        severity=rule.severity,
                        category=rule.category,
                        description=rule.description,
                        matched_content=match.group(0),
                        mitre_attack=rule.mitre_attack
                    )
                    
                    # Add packet info if available
                    if packet_info:
                        alert.src_ip = getattr(packet_info, 'src_ip', '')
                        alert.dst_ip = getattr(packet_info, 'dst_ip', '')
                        alert.src_port = getattr(packet_info, 'src_port', 0)
                        alert.dst_port = getattr(packet_info, 'dst_port', 0)
                        alert.protocol = getattr(packet_info, 'protocol', '')
                    
                    alerts.append(alert)
                    
        except Exception as e:
            logger.debug(f"Payload check error: {e}")
        
        return alerts
    
    def check_http(self, packet_info: Any) -> List[Alert]:
        """Check HTTP-specific anomalies."""
        alerts = []
        http_rules = self.protocol_rules.get("http", {})
        
        if not http_rules:
            return alerts
        
        # Check User-Agent
        user_agent = getattr(packet_info, 'http_user_agent', '')
        suspicious_agents = http_rules.get("suspicious_user_agents", [])
        
        for sus_agent in suspicious_agents:
            if sus_agent.lower() in user_agent.lower():
                alerts.append(Alert(
                    timestamp=datetime.now(),
                    rule_id="HTTP-SUSPICIOUS-UA",
                    rule_name="Suspicious User-Agent",
                    severity="medium",
                    category="reconnaissance",
                    description=f"Suspicious User-Agent detected: {user_agent}",
                    src_ip=getattr(packet_info, 'src_ip', ''),
                    dst_ip=getattr(packet_info, 'dst_ip', ''),
                    matched_content=user_agent,
                    mitre_attack="T1595"
                ))
                break
        
        # Check URI length
        uri = getattr(packet_info, 'http_uri', '')
        max_uri = http_rules.get("max_uri_length", 2048)
        if len(uri) > max_uri:
            alerts.append(Alert(
                timestamp=datetime.now(),
                rule_id="HTTP-LONG-URI",
                rule_name="Abnormally Long URI",
                severity="medium",
                category="evasion",
                description=f"URI length ({len(uri)}) exceeds maximum ({max_uri})",
                src_ip=getattr(packet_info, 'src_ip', ''),
                dst_ip=getattr(packet_info, 'dst_ip', ''),
                mitre_attack="T1190"
            ))
        
        return alerts
    
    def check_dns(self, packet_info: Any) -> List[Alert]:
        """Check DNS-specific anomalies."""
        alerts = []
        dns_rules = self.protocol_rules.get("dns", {})
        
        if not dns_rules:
            return alerts
        
        query = getattr(packet_info, 'dns_query', '')
        if not query:
            return alerts
        
        # Check query length (DNS tunneling indicator)
        max_length = dns_rules.get("max_query_length", 253)
        if len(query) > max_length:
            alerts.append(Alert(
                timestamp=datetime.now(),
                rule_id="DNS-LONG-QUERY",
                rule_name="Abnormally Long DNS Query",
                severity="high",
                category="c2",
                description=f"DNS query length ({len(query)}) indicates possible tunneling",
                src_ip=getattr(packet_info, 'src_ip', ''),
                dst_ip=getattr(packet_info, 'dst_ip', ''),
                matched_content=query[:100],
                mitre_attack="T1071.004"
            ))
        
        # Check suspicious TLDs
        suspicious_tlds = dns_rules.get("suspicious_tlds", [])
        for tld in suspicious_tlds:
            if query.rstrip('.').endswith(tld):
                alerts.append(Alert(
                    timestamp=datetime.now(),
                    rule_id="DNS-SUSPICIOUS-TLD",
                    rule_name="Suspicious TLD Query",
                    severity="low",
                    category="threat_intel",
                    description=f"Query to suspicious TLD: {tld}",
                    src_ip=getattr(packet_info, 'src_ip', ''),
                    dst_ip=getattr(packet_info, 'dst_ip', ''),
                    matched_content=query,
                    mitre_attack="T1071.004"
                ))
                break
        
        return alerts
    
    def check_tcp_flags(self, flags: str, packet_info: Any = None) -> List[Alert]:
        """Check for suspicious TCP flag combinations (scan detection)."""
        alerts = []
        
        for sig in self.network_signatures:
            sig_flags = sig.get("tcp_flags", "")
            
            # Check for specific flag patterns
            if sig_flags == "NONE" and not flags:
                # NULL scan
                alerts.append(Alert(
                    timestamp=datetime.now(),
                    rule_id=sig.get("id", "TCP-SCAN"),
                    rule_name=sig.get("name", "TCP Scan Detected"),
                    severity=sig.get("severity", "high"),
                    category="reconnaissance",
                    description=sig.get("description", "Suspicious TCP flag pattern"),
                    mitre_attack="T1046"
                ))
            elif sig_flags == "FIN,PSH,URG":
                # XMAS scan
                if all(f in flags for f in ["FIN", "PSH", "URG"]) and "SYN" not in flags and "ACK" not in flags:
                    alerts.append(Alert(
                        timestamp=datetime.now(),
                        rule_id=sig.get("id", "TCP-XMAS"),
                        rule_name=sig.get("name", "XMAS Scan Detected"),
                        severity=sig.get("severity", "high"),
                        category="reconnaissance",
                        description=sig.get("description", "XMAS scan pattern detected"),
                        mitre_attack="T1046"
                    ))
            elif sig_flags == "FIN" and flags == "FIN":
                # FIN scan
                alerts.append(Alert(
                    timestamp=datetime.now(),
                    rule_id=sig.get("id", "TCP-FIN"),
                    rule_name=sig.get("name", "FIN Scan Detected"),
                    severity=sig.get("severity", "high"),
                    category="reconnaissance",
                    description=sig.get("description", "FIN scan pattern detected"),
                    mitre_attack="T1046"
                ))
        
        if packet_info:
            for alert in alerts:
                alert.src_ip = getattr(packet_info, 'src_ip', '')
                alert.dst_ip = getattr(packet_info, 'dst_ip', '')
        
        return alerts
    
    def check_packet(self, packet_info: Any) -> List[Alert]:
        """
        Comprehensive packet analysis using all detection methods.
        This is the main entry point for packet analysis.
        """
        alerts = []
        
        # 1. Check IP blacklist
        src_ip = getattr(packet_info, 'src_ip', '')
        dst_ip = getattr(packet_info, 'dst_ip', '')
        
        for ip in [src_ip, dst_ip]:
            result = self.check_ip_blacklist(ip)
            if result:
                alerts.append(result)
        
        # 2. Check suspicious ports
        dst_port = getattr(packet_info, 'dst_port', 0)
        port_category = self.check_suspicious_port(dst_port)
        if port_category:
            alerts.append(Alert(
                timestamp=datetime.now(),
                rule_id="SUSPICIOUS-PORT",
                rule_name="Suspicious Port Activity",
                severity="medium",
                category="reconnaissance",
                description=f"Traffic to suspicious port {dst_port} ({port_category})",
                src_ip=src_ip,
                dst_ip=dst_ip,
                dst_port=dst_port,
                mitre_attack="T1571"
            ))
        
        # 3. Check payload (ONLY for plaintext traffic)
        # Skip encrypted ports (HTTPS, SSH, etc.) to avoid false positives
        encrypted_ports = {443, 8443, 22, 465, 993, 995, 636, 989, 990, 992}
        src_port = getattr(packet_info, 'src_port', 0)
        protocol = getattr(packet_info, 'protocol', '')
        is_encrypted = getattr(packet_info, 'is_encrypted', False)
        
        # Only check payload if:
        # - Not an encrypted port
        # - Not marked as encrypted
        # - Is HTTP (plaintext) or has low entropy (likely plaintext)
        should_check_payload = False
        
        if dst_port not in encrypted_ports and src_port not in encrypted_ports:
            if protocol == "HTTP":
                should_check_payload = True
            elif not is_encrypted:
                # Check entropy to detect encrypted data
                payload = getattr(packet_info, 'payload', b'')
                if payload and len(payload) > 0:
                    entropy = self._calculate_entropy(payload)
                    # Encrypted data has high entropy (>7.5), plaintext has lower
                    if entropy < 7.5:
                        should_check_payload = True
        
        if should_check_payload:
            payload = getattr(packet_info, 'payload', b'')
            if payload:
                alerts.extend(self.check_payload(payload, packet_info))
        
        # 4. Protocol-specific checks
        if protocol == "HTTP":
            alerts.extend(self.check_http(packet_info))
        elif protocol == "DNS":
            alerts.extend(self.check_dns(packet_info))
        elif protocol == "TCP":
            flags = getattr(packet_info, 'flags', '')
            alerts.extend(self.check_tcp_flags(flags, packet_info))
        
        return alerts
    
    def _calculate_entropy(self, data: bytes) -> float:
        """Calculate Shannon entropy to detect encrypted data."""
        if not data or len(data) == 0:
            return 0.0
        
        import math
        byte_counts = {}
        for byte in data:
            byte_counts[byte] = byte_counts.get(byte, 0) + 1
        
        entropy = 0.0
        length = len(data)
        for count in byte_counts.values():
            probability = count / length
            if probability > 0:
                entropy -= probability * math.log2(probability)
        
        return entropy
    
    def get_rule_stats(self) -> Dict[str, Any]:
        """Get statistics about loaded rules."""
        return {
            "total_rules": len(self.rules),
            "ip_blacklist_size": len(self.ip_blacklist),
            "suspicious_ports": {k: len(v) for k, v in self.suspicious_ports.items()},
            "categories": list(set(r.category for r in self.rules.values())),
            "severities": list(set(r.severity for r in self.rules.values()))
        }


